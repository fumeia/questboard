#!/usr/bin/env python3
"""extension/stylesheet.src.css (written for a dark popup) → extension/stylesheet.css with
.qb-dark and .qb-light variants. The theme class sits on the popup box (see extension.js
_applyTheme), so Questboard looks right whatever shell theme is installed.

St has no CSS variables, hence this small generator. Run it after editing the source
(`tools/qb pack` runs it automatically)."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "extension", "stylesheet.src.css")
OUT = os.path.join(ROOT, "extension", "stylesheet.css")

# Rules outside the popup (top bar) are emitted once, untouched.
GLOBAL = (".qb-panel-badge",)
# Text that sits on a strong colour stays white in both themes.
KEEP_WHITE = (".qb-check.checked .qb-check-icon", ".qb-day.today.selected .qb-day-num", ".qb-level-badge")

SURFACES = {
    "dark": "background-color: #242428; color: #eeeeec; border: 1px solid rgba(255,255,255,0.06);",
    "light": "background-color: #fafaf8; color: #1d1d20; border: 1px solid rgba(0,0,0,0.12);",
}

# Light-theme replacements for bright accent text that would be unreadable on white.
LIGHT_HEX = {
    "#f8e45c": "#9c6a00", "#ffa348": "#c64600", "#8ff0a4": "#1a7f37", "#99c1f1": "#1c5fb8",
    "#ff7b72": "#c01c28", "#f9f06b": "#8a6100", "#ffbe6f": "#a33a00", "#eeeeec": "#1d1d20",
}


def light_decls(decls, selector):
    def rgba(m):
        a = float(m.group(1))
        # white overlays → black overlays (slightly stronger for text, which needs contrast)
        return f"rgba(0,0,0,{round(min(0.85, a * (1.1 if a >= 0.3 else 0.9)), 3)})"
    d = re.sub(r"rgba\(255,\s*255,\s*255,\s*([0-9.]+)\)", rgba, decls)
    d = d.replace("rgba(0,0,0,0.25)", "rgba(0,0,0,0.06)")  # picker backdrop (src already uses black)
    if not any(k in selector for k in KEEP_WHITE):
        d = re.sub(r"#fff\b|#ffffff\b|\bwhite\b", "#1d1d20", d)
    for k, v in LIGHT_HEX.items():
        d = re.sub(re.escape(k) + r"\b", v, d, flags=re.I)
    return d


def main():
    src = re.sub(r"/\*.*?\*/", "", open(SRC).read(), flags=re.S)
    rules = re.findall(r"([^{}]+)\{([^{}]*)\}", src)
    out = ["/* GENERATED by tools/gen_css.py from stylesheet.src.css — edit the source, not this file. */\n"]
    for theme in ("dark", "light"):
        out.append(f".qb-{theme} {{ {SURFACES[theme]} }}\n")
    for sel, decls in rules:
        sel = " ".join(sel.split())
        decls = " ".join(decls.split())
        if sel.startswith(GLOBAL):
            out.append(f"{sel} {{ {decls} }}\n")
            continue
        parts = [p.strip() for p in sel.split(",")]
        for theme in ("dark", "light"):
            d = decls if theme == "dark" else light_decls(decls, sel)
            out.append(", ".join(f".qb-{theme} {p}" for p in parts) + f" {{ {d} }}\n")
    open(OUT, "w").write("".join(out))
    print(f"wrote {OUT} ({len(rules)} rules × 2 themes)")


if __name__ == "__main__":
    main()
